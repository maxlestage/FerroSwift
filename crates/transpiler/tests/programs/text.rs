fn main() {
    let s = "Hello, Wörld! 123";
    println!("{} {} {}", s.len(), s.chars().count(), s.to_uppercase());
    println!("{} {}", s.to_lowercase(), s.replace("l", "L"));
    println!("{} {}", s.starts_with("Hello"), s.ends_with('3'));
    println!("{:?} {:?}", s.find("Wör"), s.find('z'));
    println!("{:?}", s.split(", ").collect::<Vec<_>>());
    println!("{:?}", s.split_whitespace().collect::<Vec<_>>());
    println!("{:?}", "a-b-c-d".splitn(2, '-').collect::<Vec<_>>());
    println!("{:?}", "a-b-c-d".rsplit('-').collect::<Vec<_>>());
    println!("{:?}", "  padded  ".trim());
    println!("[{}] [{}]", "  padded  ".trim_start(), "  padded  ".trim_end());
    println!("{:?}", "xxhixx".trim_matches('x'));
    println!("{:?} {:?}", "prefix-body".strip_prefix("prefix-"), "prefix-body".strip_prefix("nope"));
    println!("{:?}", "body.txt".strip_suffix(".txt"));
    println!("{}", "ab".repeat(3));
    println!("{}", s.chars().rev().collect::<String>());
    println!("{}", s.chars().filter(|c| c.is_alphabetic()).collect::<String>());
    println!("{}", s.chars().map(|c| if c.is_ascii_digit() { '#' } else { c }).collect::<String>());
    println!("{:?}", s.char_indices().filter(|(_, c)| c.is_uppercase()).map(|(i, _)| i).collect::<Vec<_>>());
    println!("{:?}", s.bytes().take(3).collect::<Vec<u8>>());
    println!("{:?}", "line one\nline two\n\nline four".lines().collect::<Vec<_>>());
    let mut owned = String::from("abc");
    owned.push('d');
    owned.push_str("ef");
    owned.insert(0, '>');
    owned.insert_str(1, "> ");
    println!("{owned} {}", owned.len());
    let last = owned.pop();
    let first = owned.remove(0);
    println!("{:?} {:?} {}", last, first, owned);
    owned.truncate(3);
    println!("{owned}");
    owned.clear();
    println!("[{}] {}", owned, owned.is_empty());
    println!("{}", &s[7..13]);
    println!("{} {}", &s[..5], &s[15..]);
    let n: i32 = "42".parse().unwrap();
    let f: f64 = "2.5".parse().unwrap();
    let b: bool = "true".parse().unwrap();
    println!("{} {} {}", n + 1, f * 2.0, !b);
    println!("{:?} {:?}", "x".parse::<i32>().is_err(), " 7".trim().parse::<u8>());
    println!("{}", "Straße".to_uppercase());
    println!("{}", "ABC".eq_ignore_ascii_case("abc"));
    println!("{}", "hello world".split(' ').map(|w| {
        let mut c = w.chars();
        match c.next() {
            Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
            None => String::new(),
        }
    }).collect::<Vec<_>>().join(" "));
    let c = 'g';
    println!("{} {} {} {}", c as u32, (c as u8 + 1) as char, c.is_lowercase(), c.to_ascii_uppercase());
    println!("{:?} {:?}", '7'.to_digit(10), 'z'.to_digit(10));
    println!("{:?}", std::char::from_digit(5, 10));
    println!("{:?}", char::from_u32(0x41));
    println!("{}", ('a'..='e').collect::<String>());
    println!("{}", ('a'..='e').rev().step_by(2).collect::<String>());
    println!("{} {} {}", 'x'.is_alphanumeric(), ' '.is_whitespace(), '!'.is_ascii_punctuation());
    println!("{}", "a,b,,c".split(',').filter(|p| !p.is_empty()).count());
    println!("{:?}", "key=value=x".split_once('='));
    println!("{:?}", "no-equals".split_once('='));
    println!("{}", "tic-tac-toe".replacen("-", "+", 1));
    println!("{}", "abc" < "abd");
    println!("{:?}", "abc".cmp("ab"));
    println!("{}", "ab".to_string() + "cd" + &"ef".to_string());
    let mut words: Vec<String> = "the quick brown fox".split(' ').map(String::from).collect();
    words.sort_by_key(|w| w.len());
    println!("{:?}", words);
    println!("{:?}", "mississippi".matches("ss").count());
    println!("{:?}", "mississippi".chars().filter(|&c| c == 's').count());
    println!("{}", "abc".chars().all(|c| c.is_ascii_lowercase()));
    println!("{:?}", "abc".chars().nth(1));
    println!("{:?}", "abc".chars().last());
    println!("{:?}", "x y z".split(' ').last());
    println!("{}", "AbC".chars().map(|c| if c.is_uppercase() { c.to_ascii_lowercase() } else { c.to_ascii_uppercase() }).collect::<String>());
    println!("{}", "hello".contains("ell") && "hello".contains('h'));
    println!("{:?}", "a1b2c3".chars().filter(char::is_ascii_digit).collect::<String>());
    println!("{:?}", String::from_utf8(vec![104, 105]).unwrap());
    println!("{:?}", "hi".as_bytes());
    println!("{}", "hi".bytes().map(|b| b as u32).sum::<u32>());
    println!("{:?}", "tab\there".split('\t').collect::<Vec<_>>());
    println!("{}", format!("{:?}", "quote\"d\n"));
    println!("{}", "αβγ".chars().count());
    println!("{:?}", "αβγ".char_indices().collect::<Vec<_>>());
    println!("{}", "Hello".chars().map(|c| c.to_string()).collect::<Vec<_>>().join("."));
    println!("{}", String::from("x").is_empty());
    println!("{:?}", "12".parse::<i64>().map(|n| n * 2));
    let text = "one two three two one";
    let unique: std::collections::BTreeSet<&str> = text.split(' ').collect();
    println!("{:?}", unique);
    let caps = text.split(' ').map(|w| w.to_uppercase()).collect::<Vec<String>>();
    println!("{}", caps.join(" "));
    println!("{}", text.split(' ').rev().collect::<Vec<_>>().join(" "));
    println!("{:>8}|{:<8}|{:^8}|", "r", "l", "c");
    println!("{:>8}|{:<8}|{:^8}|", 42, 42, 42);
    println!("{:*^9}|{:->6}|{:_<5}|", "mid", 7, "x");
    println!("{:08.3}|{:+}|{:+.1}|{: >5}", 3.14159, 5, -2.0, 1);
    println!("{:x} {:X} {:#x} {:b} {:o} {:#b} {:08b}", 255, 255, 255, 5, 8, 5, 5);
    println!("{:e} {:E}", 1234.5, 0.00012);
    println!("{:width$}|{:.prec$}|{:>w2$.p2$}", 7, 2.0f64 / 3.0, 1.23456, width = 4, prec = 2, w2 = 8, p2 = 3);
    println!("{0} {1} {0} {name}", "a", "b", name = "n");
    println!("{{literal}} {}", 1);
    println!("{:5}|{:5}|{:<5}|", "ab", 12, 12);
    println!("{:?} {:?} {:?}", "s", 'c', 1.0);
    println!("{:>6.2}% {:3}%", 12.3456, 7);
    println!("{:#?}", vec![1, 2]);
    println!("{:?}", (1, "two", 3.0, 'c', true, None::<i32>));
    println!("{:10.3e}|", 1234.5678);
    println!("{:.0} {:.0} {:.0} {:.1}", 2.5, 3.5, -0.4, 0.05);
    println!("{} {} {} {}", 1.0, 1.5e10, 0.1 + 0.2, 1e21);
    println!("{} {} {}", f64::NAN, f64::INFINITY, -0.0f64);
    println!("{:?} {:?} {:?}", 1.0f64, 0.1 + 0.2, 1e-7);
    println!("{} {}", 100000000.0f64, 1e-5);
    println!("{} {}", 123456789012345680.0f64, 0.000001);
    println!("{}", 1.0f32 / 3.0);
    println!("{:?}", 1.0f32 / 3.0);
}
