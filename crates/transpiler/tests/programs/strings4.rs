fn main() {
    let s = "key=value=more";
    println!("{:?} {:?}", s.splitn(2, '=').collect::<Vec<_>>(), s.rsplitn(2, '=').collect::<Vec<_>>());
    println!("{:?} {:?}", s.split_once('='), s.rsplit_once('='));
    println!("{:?}", "a,b,,c,".split_terminator(',').collect::<Vec<_>>());
    println!("{:?}", "a,b,,c,".split(',').collect::<Vec<_>>());
    println!("{:?} {:?}", "xxhixx".trim_start_matches('x'), "xxhixx".trim_end_matches("xx"));
    println!("{:?} {:?}", "--a--".trim_matches('-'), "  a b  ".trim_end());
    println!("{:?} {:?} {:?}", "héllo wörld".find('w'), "héllo wörld".rfind('l'), "héllo".find("ll"));
    println!("{:?} {:?}", "hello".find(char::is_whitespace), "a b\tc".find(char::is_whitespace));
    println!("{:?}", "héllo".char_indices().rev().collect::<Vec<_>>());
    println!("{} {}", "aaa".replacen("a", "b", 2), "aXbXc".replace('X', "-"));
    println!("{:?} {:?}", "file.rs".strip_suffix(".rs"), "file.rs".strip_prefix("x"));
    println!("{} {}", "hello".starts_with('h'), "hello".ends_with(['o', 'x']));
    println!("{:?}", "abc".bytes().rev().collect::<Vec<u8>>());
    println!("{}", "a1b2c3".chars().filter(char::is_ascii_digit).collect::<String>());
    println!("{:?} {:?}", "3.5".parse::<f32>(), "x".parse::<f32>().is_err());
    println!("{} {} {}", 65u8 as char, 'a' as u8, ('a' as u8 + 2) as char);
    println!("{:?} {:?} {:?}", '\n', '\'', "tab\there");
    println!("{} {} {}", "héllo".len(), "héllo".chars().count(), "日本".len());
    let (left, right) = "hello world".split_at(5);
    println!("[{left}] [{right}] {:?}", "hello".chars().nth(1));
    println!("{:?} {:?}", "apple".cmp("banana"), "b" > "a");
    let mut t = String::from("hello");
    t.insert(0, '>');
    t.insert_str(1, "> ");
    println!("{t} {:?} {:?}", t.remove(0), t.pop());
    t.truncate(3);
    t.extend(['x', 'y']);
    t.extend(["!", "?"]);
    println!("{t} {}", t.capacity() >= t.len());
    println!("{} {}", ["a", "b", "c"].concat(), [[1, 2], [3, 4]].concat().len());
    println!("{} {}", vec!["x".to_string(), "y".to_string()].join("+"), "ab".repeat(3));
    println!("{:?}", "Hello World".chars().rev().collect::<String>());
    println!("{} {}", "Hello".eq_ignore_ascii_case("hELLO"), "ß".to_uppercase());
    println!("{:?} {:?}", "a-b_c d".split(|c: char| !c.is_alphanumeric()).collect::<Vec<_>>(), "  x  y ".split_whitespace().rev().collect::<Vec<_>>());
    println!("{:?}", "line1\nline2\r\nline3\n".lines().map(str::len).collect::<Vec<_>>());
    println!("{} {}", "abc" < "abd", "Zebra" < "apple");
    println!("{:?} {:?}", "hello".char_indices().filter(|(_, c)| *c == 'l').map(|(i, _)| i).collect::<Vec<_>>(), "hello".matches('l').count());
    println!("{:?}", "one two three".split(' ').map(|w| w.chars().rev().collect::<String>()).collect::<Vec<_>>().join(" "));
    println!("{:?} {:?}", "abc".chars().map(|c| c.to_ascii_uppercase()).collect::<Vec<_>>(), 'z'.is_alphabetic());
    println!("{} {} {}", '9'.to_digit(10).unwrap(), 'f'.to_digit(16).unwrap(), char::from_digit(7, 10).unwrap());
    println!("{:?} {:?} {:?}", char::from_u32(0x41), char::from_u32(0xD800), std::char::from_u32(0x1F600));
    println!("{} {} {}", 'é'.len_utf8(), '€' as u32, ('a'..='e').collect::<String>());
    println!("{:?} {:?}", "x".parse::<char>(), "xy".parse::<char>().is_err());
    println!("{} {:?}", "Hello".to_lowercase().contains("ell"), "hello".get(1..3));
    println!("{:?} {:?}", "hello".get(1..10), "héllo".is_char_boundary(2));
    println!("{:?}", "a b c".splitn(2, ' ').last());
    println!("{:?}", "mississippi".match_indices("ss").collect::<Vec<_>>());
    println!("{:?} {:?}", "Abc".chars().all(|c| c.is_ascii()), "Abc".chars().any(char::is_uppercase));
    let words = ["apple", "Banana", "cherry"];
    let mut sorted = words.to_vec();
    sorted.sort_by_key(|w| w.to_lowercase());
    println!("{:?} {:?}", sorted, words.iter().map(|w| w.len()).max());
    println!("{:?}", "Hello, World!".chars().filter(|c| c.is_alphabetic()).map(|c| c.to_ascii_lowercase()).collect::<String>());
    println!("{:>5}|{:<5}|{:^5}|", "ab", "cd", "e");
    println!("{}", format!("{:?}", "quote\"inside") );
    println!("{}", "tic-tac-toe".split('-').map(|p| p.to_uppercase()).collect::<Vec<_>>().join("_"));
    println!("{:?} {:?}", "abc".chars().position(|c| c == 'c'), "abc".bytes().nth(1));
    println!("{:?}", "α,β,γ".split(',').map(|s| s.chars().count()).sum::<usize>());
    let text = "the quick brown fox";
    let caps: String = text.split(' ').map(|w| { let mut c = w.chars(); match c.next() { Some(f) => f.to_uppercase().collect::<String>() + c.as_str(), None => String::new() } }).collect::<Vec<_>>().join(" ");
    println!("{caps}");
    println!("{:?}", text.char_indices().filter(|(_, c)| c.is_whitespace()).map(|(i, _)| i).collect::<Vec<_>>());
    println!("{:?} {:?}", "abc".as_bytes(), String::from_utf8(vec![104, 105]).unwrap());
    println!("{:?} {:?}", "abcdef".chars().step_by(2).collect::<String>(), "abcdef".chars().skip(1).step_by(2).collect::<String>());
    println!("{} {}", "x".is_empty(), "".chars().next().is_none());
    println!("{:?} {:?}", "ab".chars().cycle().take(5).collect::<String>(), "abc".chars().last());
    println!("{:?}", "a=1;b=2".split(';').filter_map(|kv| kv.split_once('=')).map(|(k, v)| (k, v.parse::<i32>().unwrap())).collect::<Vec<_>>());
    println!("{:?}", "hello"[1..].to_string() + &"world"[..2]);
    println!("{}", "x".cmp("y") == std::cmp::Ordering::Less);
    println!("{:?} {:?}", "ABC".to_lowercase().as_str() == "abc", "abc".chars().map(|c| ((c as u8) ^ 0x20) as char).collect::<String>());
    println!("{:?} {:?}", "title case".split(' ').map(|w| w.len()).collect::<Vec<_>>(), "ab cd".split(' ').flat_map(|w| w.chars()).collect::<Vec<_>>());
    println!("{:?}", "a\tb".escape_default().to_string());
    println!("{:?} {:?}", "bob".chars().eq("bob".chars().rev()), "abc".chars().eq("abc".chars().rev()));
    println!("{:?}", "x".chars().chain("yz".chars()).collect::<String>());
    println!("{}", "hello world".split(' ').map(|w| w.chars().rev().collect::<String>()).collect::<Vec<_>>().concat());
    println!("{}", "aXbXc".split('X').count());
    println!("{:?}", "Mary had a little lamb".split(' ').max_by_key(|w| w.len()));
    println!("{:?}", "zebra".chars().min());
    println!("{:?} {:?}", "12abc".trim_start_matches(char::is_numeric), "abc12".trim_end_matches(|c: char| c.is_ascii_digit()));
}
