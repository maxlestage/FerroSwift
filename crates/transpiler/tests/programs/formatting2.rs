fn main() {
    println!("{:x} {:X} {:b} {:o}", -1i32, -255i32, -2i8, -8i16);
    println!("{:#x} {:#b} {:08x} {:>6x}|", -16i64, 5u8, 255u32, 4095);
    println!("{:x} {:x} {:X}", i32::MIN, u64::MAX, 0xDEADu32);
    println!("{:e} {:e} {:E} {:.3e}", -1500.0, 0.0, 123u32, -0.000123);
    println!("{:.0} {:.0} {:.0} {:.0} {:.1} {:.1} {:.2}", 0.5, 1.5, 2.5, -2.5, 0.25, 0.35, 1.005);
    println!("{} {} {} {}", 0.1 + 0.2, 1e-7, 123456789012345680.0, 5e-324);
    println!("{} {} {}", f32::MAX, f32::MIN_POSITIVE, 1.0e-10f32);
    println!("{:?} {:?} {:?}", 1e-7, 1e21, f64::EPSILON);
    println!("{:>+8.2} {:<+8.1}| {:^+9.3}|", 3.14159, -2.0, 1.0);
    println!("{:+} {:+} {:+.1} {:+08.2}", 0, -0.0, 0.0, -1.5);
    println!("{} {} {} {}", 7u32.saturating_sub(9), u32::MAX.wrapping_add(2), (-128i8).wrapping_neg(), (-128i8).wrapping_abs());
    println!("{:?} {:?} {} {}", i32::MIN.checked_abs(), 5i32.checked_neg(), (-5i32).abs(), i64::MAX.saturating_mul(2));
    println!("{} {} {} {}", 200u8 as i8, -1i8 as u8, 300u16 as u8, -200i32 as u8);
    println!("{} {} {:.4} {:.4}", 2.0f64.powi(-2), 3.0f64.hypot(4.0), 1.0f64.atan2(1.0), 180f64.to_radians());
    println!("{:.6} {:.6} {:.3}", 1.0f64.sin(), std::f64::consts::E.ln(), 100f64.log10());
    println!("{} {} {}", (2.5f64).to_string(), (1.0f64 / 0.0).to_string(), (-0.0f64).to_string());
    println!("{} {} {}", 10f64.sqrt() as i32, (2.0f64).mul_add(3.0, 1.0), 7.0f64 % 2.5);
    let s = "héllo wörld";
    println!("{} {} {}", s.len(), s.chars().count(), s.to_uppercase());
    println!("{} {} {}", "ß".to_uppercase(), "ǆ".to_uppercase(), "İ".to_lowercase().chars().count());
    let family = "👨\u{200d}👩\u{200d}👧";
    println!("{} {} {}", family.len(), family.chars().count(), family.chars().filter(|c| *c != '\u{200d}').count());
    let combined = "e\u{301}a";
    println!("{} {} {:?}", combined.len(), combined.chars().count(), combined.chars().rev().collect::<String>().len());
    println!("{:?} {:?}", combined.chars().next(), combined.chars().nth(1).map(|c| c as u32));
    println!("{:?} {:?} {:?}", "\u{1b}[0m", '\u{7f}', "tab\t\u{0}end");
    println!("{:?} {:?}", 'é', "naïve café".chars().filter(|c| !c.is_ascii()).count());
    println!("{:?}", "a-b_c d".split(|c: char| c == '-' || c == '_' || c == ' ').collect::<Vec<_>>());
    println!("{:?}", "Hello World".char_indices().filter(|(_, c)| c.is_uppercase()).map(|(i, _)| i).collect::<Vec<_>>());
    println!("{}", "abc".chars().map(|c| ((c as u8) ^ 0x20) as char).collect::<String>());
    println!("{:?} {:?}", "x".cmp("y"), "b".partial_cmp("a"));
    println!("{} {}", 'a' < 'b', "apple" > "Apple");
    println!("{:?}", "mixed CASE".chars().map(|c| if c.is_lowercase() { c.to_ascii_uppercase() } else { c.to_ascii_lowercase() }).collect::<String>());
    println!("{:5}|{:<5}|{:>5}|{:^5}|{:.2}|", "ab", "ab", "ab", "ab", "abcdef");
    println!("{:*^9}|{:->6}|{:_<4}|", "mid", 42, "x");
    println!("{:>3}|{:<3}|", 12345, "longer");
    println!("{0:?} {0} {1:?} {1}", "q\"uote", 'q');
}
