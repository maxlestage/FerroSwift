fn main() {
    let bytes = [0u8, 15, 255, 128];
    println!("{:x?} {:X?} {:02x?} {:#x?}", bytes, bytes, bytes, bytes);
    println!("{:x?} {:?}", vec![Some(255u8), None], (10u8, 11u8));
    println!("{:#x?}", (255u16, "s"));
    println!("[{:+.3e}] [{:10.3e}] [{:<10.1e}] [{:e}]", 1234.5678, 0.000123, 98765.0, 1.0f32);
    println!("[{:^9.3}] [{:>7.2}] [{:3.1}] [{:#>5}]", "abcdef", "héllo", "xyz", "é");
    println!("{:?} {:?} {:?}", format!("{:5}", 'c'), format!("{:<3}", true), format!("{:>4?}", ()));
    println!("{:05.1} {:+05} {:08.3} {:+08.2}", -1.25, 7, -2.5, 3.14159);
    println!("{:#?}", vec![(1, "a"), (2, "b")]);
    println!("{:#?}", Some(vec![Some(1), None]));
    println!("[{:>8?}] [{:<6?}] [{:^7?}]", Some(1), "ab", 'c');
    println!("[{:>8?}] [{:5?}] [{:03?}]", vec![1, 2], (1, 2), -7);
    println!("[{:x}] [{:#X}] [{:#b}] [{:o}] [{:#o}] [{:08b}] [{:#010b}]", 255u8, 255, 5, 64, 64, 5u8, 5u8);
    println!("[{:x}] [{:X}] [{:b}]", -1i8, -256i16, -2i32);
    println!("[{:e}] [{:E}] [{:.2e}] [{:e}] [{:e}]", 0.0, 123456789.0, 0.00001234, 42, 100u64);
    println!("[{:10}] [{:<10}] [{:^10}] [{:>10}]", 3.5, -3.5, 1e10, 1e-7);
    println!("[{}] [{}] [{}] [{:?}] [{:?}]", 1e16, 1e15, 1.5e-5, 1e16, 1e-7);
    println!("[{}] [{:?}] [{}] [{:?}]", f64::NAN, f64::INFINITY, -f64::INFINITY, -0.0);
    println!("[{:5}] [{:<5}] [{:^5}] [{:05}]", f64::NAN, f64::INFINITY, -f64::INFINITY, -f64::INFINITY);
    println!("[{:+}] [{:+}] [{:+.1}] [{:+?}]", 0, -0.0, 0.0, 5);
    println!("[{:.0}] [{:.0}] [{:.0}] [{:.1}] [{:.1}]", 0.5, 1.5, 2.5, 0.25, 0.35);
    println!("[{:.2}] [{:.3}] [{:.1}]", 1.005, 2.0005, 0.05);
    let width = 7;
    let prec = 2;
    println!("[{:width$.prec$}] [{:>width$}] [{:.prec$?}] [{3:4$}]", 3.14159, "ab", 2.0, 9, 4);
    println!("[{:>1$}] [{:.*}] [{:>5$.4$}]", "x", 3, 1.23456, 4.0, 6, 7);
}
