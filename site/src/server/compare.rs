//! The Rust/Swift comparisons of the home page. The Swift side is produced by the transpiler
//! when the site is generated, so it always shows what FerroSwift really writes.

use std::sync::OnceLock;

use crate::highlight::{Syntax, highlight};

/// A Rust snippet and its translation, highlighted.
pub struct Comparison {
    pub rust_file: &'static str,
    pub swift_file: &'static str,
    pub rust: &'static str,
    pub swift: String,
    pub rust_html: String,
    pub swift_html: String,
    /// What the program prints, when it prints something.
    pub output: Option<&'static str>,
}

struct Snippet {
    rust_file: &'static str,
    swift_file: &'static str,
    source: &'static str,
    output: Option<&'static str>,
}

const HERO: Snippet = Snippet {
    rust_file: "hello.rs",
    swift_file: "Hello.swift",
    source: r#"use ferroswift::prelude::*;

#[derive(View, Default)]
struct Hello {
    #[state]
    name: String,
}

impl View for Hello {
    fn body(&mut self) -> impl View {
        vstack()
            .child(text_field("Name", &mut self.name))
            .child(text(format!("Hello, {}!", self.name)))
            .padding()
    }
}"#,
    output: None,
};

/// The tabs of the "side by side" section, in the order of `Home::tabs`.
