/// The comment the transpiler writes before its support code.
const SUPPORT_MARK: &str = "// MARK: - FerroSwift support";

/// The Swift worth showing: without the "generated" header, the support code and, when
/// `short`, the imports.
fn tidy(swift: &str, short: bool) -> String {
    let code = swift.split(SUPPORT_MARK).next().unwrap_or(swift);
    let lines: Vec<&str> = code
        .lines()
        .filter(|l| !l.starts_with("// Generated by FerroSwift"))
        .filter(|l| !(short && l.starts_with("import ")))
        .collect();
    lines.join("\n").trim().to_string()
}

fn build(snippet: &Snippet, short: bool) -> Comparison {
    let source = snippet.source;
    let out = ferroswift_transpiler::transpile(source);
    let swift = tidy(&out.swift, short);
    Comparison {
        rust_file: snippet.rust_file,
        swift_file: snippet.swift_file,
        rust: source,
        rust_html: highlight(source, Syntax::Rust),
        swift_html: highlight(&swift, Syntax::Swift),
        swift,
        output: snippet.output,
    }
}

/// The small comparison of the hero.
pub fn hero() -> &'static Comparison {
    static HERO_CMP: OnceLock<Comparison> = OnceLock::new();
    HERO_CMP.get_or_init(|| build(&HERO, true))
}

/// The comparisons of the "side by side" section.
pub fn tabs() -> &'static [Comparison] {
    static ALL: OnceLock<Vec<Comparison>> = OnceLock::new();
    ALL.get_or_init(|| TABS.iter().map(|s| build(s, false)).collect())
}

/// Every snippet with its diagnostics (tests).
pub fn diagnostics() -> Vec<(&'static str, Vec<ferroswift_transpiler::Diagnostic>)> {
    std::iter::once(&HERO)
        .chain(TABS.iter())
        .map(|s| {
            (
                s.rust_file,
                ferroswift_transpiler::transpile(s.source).diagnostics,
            )
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_snippet_translates_without_diagnostics() {
        for (file, diagnostics) in diagnostics() {
            assert!(diagnostics.is_empty(), "{file}: {diagnostics:?}");
        }
        let hero = hero();
        assert!(hero.swift.contains("@State var name"), "{}", hero.swift);
        assert!(!hero.swift.contains("import"));
        assert!(!hero.swift.contains("Generated by FerroSwift"));
        let tabs = tabs();
        assert!(
            tabs[0]
                .swift
                .contains("Toggle(\"Notifications\", isOn: $notifications)")
        );
        assert!(tabs[1].swift.contains("switch payment"));
        assert!(tabs[2].swift.contains("throws(LoginError)"));
        assert!(tabs[3].swift.contains("rsDebug"));
        assert!(!tabs[3].swift.contains(SUPPORT_MARK));
    }
}
